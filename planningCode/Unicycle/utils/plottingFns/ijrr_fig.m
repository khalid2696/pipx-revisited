function fig = ijrr_fig(span, aspect)
%IJRR_FIG Create a figure sized and styled for IJRR (sagej, two-column).
%   fig = ijrr_fig('single')        % one column, height = 0.75*width
%   fig = ijrr_fig('double', 0.35)  % full text width, wide and short
%
%   Text sizes are physical: include the PDF in LaTeX WITHOUT a width
%   argument (\includegraphics{fig.pdf}) so 8 pt stays 8 pt in print.
%
%   Set W_SINGLE / W_DOUBLE from your own .tex file:
%       \showthe\columnwidth   and   \showthe\textwidth
%   (values in pt; divide by 72.27 to get inches).

arguments
    span   (1,:) char {mustBeMember(span, {'single', 'double'})} = 'single'
    aspect (1,1) double {mustBePositive} = 0.75
end

% ---- Page geometry (inches) -- REPLACE with measured values ----------
W_SINGLE = 3.35;
W_DOUBLE = 495.07794 / 72.27;   % = 6.850 in, measured \textwidth

% ---- Typography ------------------------------------------------------
FS_LABEL = 8;     % axis labels, legend, annotations (matches caption size)
FS_TICK  = 7;     % tick labels (never below 6)

fontName = 'Nimbus Roman';                  % sagej body font is Times
%Use 'Helvetica' or 'Arial' if needed
if ~any(strcmp(listfonts, fontName))
    fontName = 'Times';
    warning('ijrr_fig:font', 'Times New Roman not found; using "%s".', fontName);
end

% ---- Strokes ---------------------------------------------------------
LW_DATA = 1.2;    % data lines (pt)
LW_AXES = 0.5;    % axes, ticks, grid (pt)
MS      = 4;      % marker size (pt)

if strcmp(span, 'single'), w = W_SINGLE; else, w = W_DOUBLE; end
h = aspect * w;

fig = figure('Units', 'inches', 'Position', [1 1 w h], 'Color', 'w', ...
    'PaperUnits', 'inches', 'PaperSize', [w h], 'PaperPosition', [0 0 w h]);

% Figure-level defaults: inherited by every axes/legend created in this
% figure only, so global MATLAB settings are left untouched.
set(fig, ...
    'DefaultAxesFontName',                 fontName, ...
    'DefaultAxesFontSize',                 FS_TICK, ...
    'DefaultAxesLabelFontSizeMultiplier',  FS_LABEL / FS_TICK, ...
    'DefaultAxesTitleFontSizeMultiplier',  FS_LABEL / FS_TICK, ...
    'DefaultAxesTitleFontWeight',          'normal', ...
    'DefaultAxesLineWidth',                LW_AXES, ...
    'DefaultAxesBox',                      'on', ...
    'DefaultAxesTickLength',               [0.015 0.015], ...
    'DefaultAxesTickLabelInterpreter',     'tex', ...
    'DefaultAxesGridAlpha',                0.15, ...
    'DefaultTextFontName',                 fontName, ...
    'DefaultTextFontSize',                 FS_LABEL, ...
    'DefaultTextInterpreter',              'tex', ...
    'DefaultLegendFontName',               fontName, ...
    'DefaultLegendFontSize',               FS_LABEL, ...
    'DefaultLegendFontSizeMode',           'manual', ...
    'DefaultLegendInterpreter',            'tex', ...
    'DefaultLegendBox',                    'off', ...
    'DefaultLineLineWidth',                LW_DATA, ...
    'DefaultLineMarkerSize',               MS, ...
    'DefaultConstantLineLineWidth',        LW_AXES);
end
